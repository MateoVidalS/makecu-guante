import generated from './demo.generated.json?raw';
import type { Calibration, AssistDirection } from '../contracts/calibration';
import type { AttemptResult, SessionSummary } from '../contracts/engine';
import type { EvaluationResult } from '../contracts/evaluation';
import type {
  Profile,
  Evaluation,
  Session,
  SessionDetail,
  Summary,
  TranscriptLine,
} from '../contracts/api';
import type { CoachDecision, FeelingEntry } from '../contracts/therapist';

export interface DemoStory {
  profile: Profile;
  calibration: Calibration;
  legacy_calibration: Calibration;
  sessions: {
    assist_direction: AssistDirection;
    started_at: string;
    ended_at: string;
    plan: Session['plan'];
    settings: Session['settings'];
    attempts: AttemptResult[];
    summary: SessionSummary;
    decisions: CoachDecision[];
    feelings: FeelingEntry[];
    transcript?: TranscriptLine[];
  }[];
  evaluations: EvaluationResult[];
}

// Generated by the backend's deterministic historical demo story. Regenerate with:
// node frontend/src/mocks/generate-demo.mjs
export const referenceDemo = JSON.parse(generated) as {
  endDate: string;
  story: DemoStory;
};

/** Move the whole story by UTC days, retaining its irregular spacing and trace timing. */
export function demoOnDate(endDate = new Date().toISOString()): DemoStory {
  const day = 86_400_000;
  const shift =
    (Math.floor(Date.parse(endDate) / day) -
      Math.floor(Date.parse(referenceDemo.endDate) / day)) *
    day;
  const story = structuredClone(referenceDemo.story);
  const shifted = (iso: string) =>
    new Date(Date.parse(iso) + shift).toISOString();
  // Traces use relative seconds. Only these record timestamps need to move.
  story.calibration.created_at = shifted(story.calibration.created_at);
  story.legacy_calibration.created_at = shifted(
    story.legacy_calibration.created_at,
  );
  for (const session of story.sessions) {
    session.started_at = shifted(session.started_at);
    session.ended_at = shifted(session.ended_at);
    for (const attempt of session.attempts) {
      attempt.started_at = shifted(attempt.started_at);
      attempt.ended_at = shifted(attempt.ended_at);
    }
    for (const decision of session.decisions) decision.t = shifted(decision.t);
    for (const feeling of session.feelings) feeling.t = shifted(feeling.t);
    for (const line of session.transcript ?? []) line.t = shifted(line.t);
  }
  for (const evaluation of story.evaluations) {
    evaluation.started_at = shifted(evaluation.started_at);
    evaluation.ended_at = shifted(evaluation.ended_at);
  }
  return story;
}

/** Adapt generated records to the REST shapes, just as seed_demo.py does on insertion. */
export function createDemoState(endDate = new Date().toISOString()) {
  const story = demoOnDate(endDate);
  // Calibration times come from the story (already shifted), as in seed_demo.py.
  const calibration = { ...story.calibration, id: 1 };
  const legacyCalibration = { ...story.legacy_calibration, id: 2 };
  let attemptId = 0;
  const traces: Record<number, AttemptResult['trace']> = {};
  const details: Record<
    number,
    SessionDetail & {
      coach_decisions: CoachDecision[];
      feelings: FeelingEntry[];
    }
  > = {};
  const sessions = story.sessions.map((value, index): Session => {
    const id = index + 1;
    const previous = story.sessions
      .slice(0, index)
      .reverse()
      .find((s) => s.assist_direction === value.assist_direction);
    const session: Session = {
      id,
      mode: 'exercise',
      started_at: value.started_at,
      ended_at: value.ended_at,
      calibration_id:
        value.assist_direction === 'open'
          ? calibration.id
          : legacyCalibration.id,
      assist_direction: value.assist_direction,
      plan: value.plan,
      settings: value.settings,
      is_demo: true,
      summary: {
        ...value.summary,
        previous: !previous
          ? null
          : {
              active_ratio_mean: previous.summary.active_ratio_mean,
              per_finger: previous.summary.per_finger.map(
                ({ finger, active_max_mean }) => ({
                  finger,
                  active_max_mean,
                }),
              ),
            },
      },
      n_attempts: value.attempts.length,
    };
    details[id] = {
      ...session,
      attempts: value.attempts.map(({ trace, ...attempt }) => {
        traces[++attemptId] = trace;
        return { ...attempt, id: attemptId, session_id: id };
      }),
      transcript: value.transcript ?? [],
      coach_decisions: value.decisions
        .map((d) => ({ ...d, session_id: id }))
        .sort((a, b) => a.t.localeCompare(b.t)),
      feelings: value.feelings.map((f) => ({ ...f, session_id: id })),
    };
    return session;
  });
  return {
    profile: story.profile,
    calibrations: [calibration, legacyCalibration],
    sessions: sessions.reverse(),
    details,
    traces,
    evaluations: story.evaluations
      .map((e, index): Evaluation => ({
        ...e,
        id: index + 1,
        calibration_id: 1,
        assist_direction: 'open',
        is_demo: true,
      }))
      .reverse(),
    // No generated Gemini summary exists in the backend seed either.
    summaries: [] as Summary[],
  };
}
